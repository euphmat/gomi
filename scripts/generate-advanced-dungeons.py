def validate(catalog: dict) -> None:
    ids: set[str] = set()
    for dungeon in catalog["dungeons"]:
        assert len(dungeon["monsters"]) == 8, f"{dungeon['id']} must have 8 monsters"
        assert dungeon["id"] not in ids, f"duplicate id: {dungeon['id']}"
        ids.add(dungeon["id"])
        for monster in dungeon["monsters"]:
            assert monster["element"] in ELEMENT_LABELS, f"invalid element: {monster['element']}"
            assert monster["weakness"] in ELEMENT_LABELS, f"invalid weakness: {monster['weakness']}"
            assert monster["ailment"] in AILMENTS, f"invalid ailment: {monster['ailment']}"
            assert len(monster["materials"]) == 3, f"{monster['id']} must have 3 materials"
            generated_ids = [
                monster["id"],
                *(f"mat_{monster['id']}_{suffix}" for suffix, _ in monster["materials"]),
                *(f"{monster['id']}_{suffix}" for suffix in ("weapon", "armor", "shield", "accessory")),
            ]
            for item_id in generated_ids:
                assert item_id not in ids, f"duplicate id: {item_id}"
                ids.add(item_id)


def generate_content(catalog: dict) -> str:
    specs = json.dumps(catalog["dungeons"], ensure_ascii=False, indent=2)
    return f"""// This file is generated by scripts/generate-advanced-dungeons.py.
// Edit advanced-dungeon-catalog.json, then rerun the generator.

const ADVANCED_DUNGEON_SPECS = {specs};

const MAGIC_ELEMENTS = new Set(['water', 'ice', 'thunder', 'light', 'dark']);
const ELEMENT_NAMES = {{ fire: '炎', water: '水', grass: '草', ice: '氷', thunder: '雷', wind: '風', earth: '土', light: '光', dark: '闇' }};
const AILMENT_NAMES = {{ poison: '毒', burn: '火傷', paralysis: '麻痺', sleep: '睡眠', confusion: '混乱', curse: '呪い', blind: '暗闇', silence: '沈黙' }};

function createAdvancedAction(monster, tier, isBoss) {{
  const multiplier = 10 + Math.floor(tier / 8) * 0.8 + (isBoss ? 2 : 0);
  return {{
    name: monster.action,
    chance: isBoss ? 45 : 35,
    description: `${{ELEMENT_NAMES[monster.element]}}属性の${{isBoss ? '全体' : '強力な'}}固有攻撃。${{AILMENT_NAMES[monster.ailment]}}を付与することがある。`,
    execute: (attacker, defender, battle) => {{
      const originalElements = attacker.stats.attackElements;
      const originalAilments = attacker.stats.attackAilments;
      attacker.stats.attackElements = {{ [monster.element]: 100 }};
      attacker.stats.attackAilments = {{ ...(originalAilments || {{}}), [monster.ailment]: isBoss ? 65 : 45 }};
      const targets = isBoss && Array.isArray(battle.party)
        ? battle.party.filter(target => !target.isDead)
        : [defender];
      targets.forEach((target, index) => battle.executeAttack(attacker, target, false, {{
        actionName: monster.action,
        damageMultiplier: multiplier,
        isMagic: MAGIC_ELEMENTS.has(monster.element),
        damageType: 'skill',
        hideActionName: index > 0,
      }}));
      attacker.stats.attackElements = originalElements;
      attacker.stats.attackAilments = originalAilments;
    }},
  }};
}}

function materialId(monster, material) {{
  return `mat_${{monster.id}}_${{material[0]}}`;
}}

function roundStat(value) {{
  return Math.round(value / 10) * 10;
}}

const ENTRIES = ADVANCED_DUNGEON_SPECS.flatMap((dungeon, dungeonIndex) =>
  dungeon.monsters.map((monster, floorIndex) => ({{
    dungeon,
    dungeonIndex,
    monster,
    floorIndex,
    tier: dungeonIndex * 8 + floorIndex,
    isBoss: floorIndex === dungeon.monsters.length - 1,
  }}))
);

export const ADVANCED_DUNGEONS = ADVANCED_DUNGEON_SPECS.map(dungeon => ({{
  id: dungeon.id,
  name: dungeon.name,
  description: dungeon.description,
  bgImage: dungeon.bgImage,
  theme: dungeon.theme,
  isUnlocked: false,
  floors: dungeon.monsters.map((monster, index) => ({{
    level: index + 1,
    monsters: index === 0 || index === dungeon.monsters.length - 1
      ? [{{ [monster.id]: 1, weight: 100 }}]
      : [
          {{ [monster.id]: 1, weight: 65 }},
          {{ [dungeon.monsters[index - 1].id]: 1, [monster.id]: 1, weight: 35 }},
        ],
  }})),
}}));

export const ADVANCED_MONSTERS = ENTRIES.map(({{ monster, tier, isBoss }}) => {{
  const growth = 1.025 ** tier;
  const bossGrowth = isBoss ? 1.8 : 1;
  return {{
    id: monster.id,
    name: monster.name,
    stats: {{
      hp: roundStat(3300000 * growth * bossGrowth),
      atk: roundStat(38000 * (1.023 ** tier) * (isBoss ? 1.3 : 1)),
      def: roundStat(32000 * (1.022 ** tier) * (isBoss ? 1.25 : 1)),
      matk: roundStat(36000 * (1.023 ** tier) * (isBoss ? 1.3 : 1)),
      mdef: roundStat(33000 * (1.022 ** tier) * (isBoss ? 1.25 : 1)),
      spd: 650 + tier * 11 + (isBoss ? 80 : 0),
    }},
    elements: {{ [monster.element]: 150, [monster.weakness]: -200 }},
    ailments: {{ [monster.ailment]: isBoss ? 70 : 45 }},
    rewards: {{
      exp: 3200 + tier * 140 + (isBoss ? 1800 : 0),
      jp: 850 + tier * 35 + (isBoss ? 450 : 0),
      gold: 1600 + tier * 80 + (isBoss ? 1000 : 0),
    }},
    drops: monster.materials.map((material, index) => ({{
      itemId: materialId(monster, material),
      rate: [5, 1, 0.1][index],
    }})),
    actions: [createAdvancedAction(monster, tier, isBoss)],
  }};
}});

export const ADVANCED_MATERIALS = ENTRIES.flatMap(({{ monster }}) =>
  monster.materials.map(material => ({{ id: materialId(monster, material), name: material[1] }}))
);

function equipmentBase(entry) {{
  const {{ dungeonIndex, monster, tier, isBoss }} = entry;
  const power = 540 + tier * 12 + (isBoss ? 25 : 0);
  const elementPower = Math.min(45, 25 + Math.floor(dungeonIndex / 2) * 5);
  const materialIds = monster.materials.map(material => materialId(monster, material));
  const price = 320000 + tier * 10000 + (isBoss ? 50000 : 0);
  return {{ power, elementPower, materialIds, price }};
}}

function recipe(price, materialIds, firstIndex, secondIndex) {{
  return {{
    price,
    materials: [
      {{ id: materialIds[firstIndex], amount: 40 }},
      {{ id: materialIds[secondIndex], amount: 10 }},
    ],
  }};
}}

export const ADVANCED_WEAPONS = ENTRIES.map(entry => {{
  const {{ monster }} = entry;
  const {{ power, elementPower, materialIds, price }} = equipmentBase(entry);
  return {{
    id: `${{monster.id}}_weapon`,
    name: monster.weapon,
    stats: {{ atk: power, matk: roundStat(power * 0.7), spd: roundStat(power * 0.48) }},
    elements: {{ [monster.element]: elementPower }},
    recipe: recipe(price, materialIds, 0, 1),
  }};
}});

export const ADVANCED_ARMORS = ENTRIES.map(entry => {{
  const {{ monster }} = entry;
  const {{ power, elementPower, materialIds, price }} = equipmentBase(entry);
  return {{
    id: `${{monster.id}}_armor`,
    name: `${{monster.gearTheme}}の戦装`,
    stats: {{ def: power, mdef: roundStat(power * 0.7) }},
    elements: {{ [monster.element]: elementPower }},
    recipe: recipe(price, materialIds, 1, 2),
  }};
}});

export const ADVANCED_SHIELDS = ENTRIES.map(entry => {{
  const {{ monster }} = entry;
  const {{ power, elementPower, materialIds, price }} = equipmentBase(entry);
  return {{
    id: `${{monster.id}}_shield`,
    name: `${{monster.gearTheme}}の護盾`,
    stats: {{ def: power, hp: roundStat(power * 0.55) }},
    elements: {{ [monster.element]: elementPower }},
    recipe: recipe(price, materialIds, 0, 2),
  }};
}});

export const ADVANCED_ACCESSORIES = ENTRIES.map(entry => {{
  const {{ monster }} = entry;
  const {{ power, elementPower, materialIds, price }} = equipmentBase(entry);
  return {{
    id: `${{monster.id}}_accessory`,
    name: `${{monster.gearTheme}}の秘宝`,
    stats: {{ matk: power, spd: roundStat(power * 0.5) }},
    elements: {{ [monster.element]: elementPower }},
    recipe: recipe(price, materialIds, 1, 2),
  }};
}});
"""


def md_escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    result = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    result.extend("| " + " | ".join(md_escape(str(cell)) for cell in row) + " |" for row in rows)
    return result


def generate_doc(catalog: dict) -> str:
    dungeons = catalog["dungeons"]
    monster_count = sum(len(d["monsters"]) for d in dungeons)
    material_count = monster_count * 3
    equipment_count = monster_count * 4
    lines = [
        "# 追加ダンジョン画像仕様一覧",
        "",
        "> この文書は `js/definitions/advanced-dungeon-catalog.json` から自動生成しています。ID・名称を変更した場合は `python3 scripts/generate-advanced-dungeons.py` を実行してください。",
        "",
        "## 共通仕様",
        "",
        "- 対象: 今回実装した9ダンジョンのモンスター・素材・武器・防具・盾・アクセサリ。",
        "- 推奨形式: WebP、正方形、背景透過。元データは512×512px以上、ゲーム配置用は128×128px程度を想定。",
        "- 画風: 既存アセットに合わせた高密度な後期16bit〜初期32bit風JRPGピクセルアート。輪郭と材質が小サイズでも判別できること。",
        "- 禁止: 文字、数字、ロゴ、透かし、額縁、UI、複数アイテムを並べた構図。画像は対象1点を中央配置すること。",
        "- 保存先は各表の `パス` を使用すること。ファイル名はIDと完全一致させること。",
        "",
        "## 件数",
        "",
        *table(["カテゴリ", "枚数"], [
            ["モンスター", str(monster_count)],
            ["素材", str(material_count)],
            ["武器", str(monster_count)],
            ["防具", str(monster_count)],
            ["盾", str(monster_count)],
            ["アクセサリ", str(monster_count)],
            ["合計", str(monster_count + material_count + equipment_count)],
        ]),
    ]
    for dungeon in dungeons:
        lines.extend(["", f"## {dungeon['name']} (`{dungeon['id']}`)", "", "### モンスター", ""])
        monster_rows = []
        material_rows = []
        equipment_rows = {"武器": [], "防具": [], "盾": [], "アクセサリ": []}
        for monster in dungeon["monsters"]:
            element = ELEMENT_LABELS[monster["element"]]
            monster_rows.append([
                f"`{monster['id']}`",
                monster["name"],
                f"`assets/monster/{monster['id']}.webp`",
                monster["concept"],
            ])
            material_ids = []
            for suffix, name in monster["materials"]:
                item_id = f"mat_{monster['id']}_{suffix}"
                material_ids.append(item_id)
                material_rows.append([
                    f"`{item_id}`",
                    name,
                    f"`assets/material/{item_id}.webp`",
                    f"{monster['name']}由来の「{name}」を単体で描く。名称から分かる身体部位・魔力・遺物の材質を強調した素材アイコン。",
                ])
            equipment = [
                ("武器", f"{monster['id']}_weapon", monster["weapon"], "assets/weapon", "武器全体の形状が読める斜め向きの装備アイコン"),
                ("防具", f"{monster['id']}_armor", f"{monster['gearTheme']}の戦装", "assets/armor", "胴装備を正面寄りに見せた装備アイコン"),
                ("盾", f"{monster['id']}_shield", f"{monster['gearTheme']}の護盾", "assets/shield", "盾面の意匠が読める正面寄りの装備アイコン"),
                ("アクセサリ", f"{monster['id']}_accessory", f"{monster['gearTheme']}の秘宝", "assets/accessory", "宝飾と魔力核が判別できる単体アクセサリアイコン"),
            ]
            for category, item_id, name, directory, framing in equipment:
                equipment_rows[category].append([
                    f"`{item_id}`",
                    name,
                    f"`{directory}/{item_id}.webp`",
                    f"{monster['name']}の意匠と{element}属性の色・発光を取り入れた{framing}。",
                ])
        lines.extend(table(["ID", "名称", "パス", "用意すべき画像"], monster_rows))
        lines.extend(["", "### 素材", ""])
        lines.extend(table(["ID", "名称", "パス", "用意すべき画像"], material_rows))
        for category in ("武器", "防具", "盾", "アクセサリ"):
            lines.extend(["", f"### {category}", ""])
            lines.extend(table(["ID", "名称", "パス", "用意すべき画像"], equipment_rows[category]))
    lines.extend(["", "## 実装済み背景", ""])
    lines.extend(table(["ダンジョンID", "背景パス"], [[f"`{d['id']}`", f"`{d['bgImage']}`"] for d in dungeons]))
    lines.append("")
    return "\n".join(lines)


