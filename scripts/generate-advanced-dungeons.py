def prompt_filename(batch_number: int, batch: list[dict[str, str]]) -> str:
    categories = list(dict.fromkeys(entry["category"] for entry in batch))
    slug = "-".join(CATEGORY_SLUGS[category] for category in categories)
    return f"5x5_{batch_number:03d}_{slug}.md"


def generate_grid_prompt(batch_number: int, batch: list[dict[str, str]], total_batches: int) -> str:
    lines = [
        f"# JRPG Ultra-Detailed High-Density Pixel Art Icon Grid — Batch {batch_number:03d}/{total_batches:03d}",
        "",
        "Please generate a single, high-resolution image perfectly formatted as a structured **5x5 grid** of individual, highly detailed pixel art assets. This image is for a professional game asset pack and MUST adhere to the following strict requirements.",
        "",
        "## CORE ABSOLUTE REQUIREMENTS",
        "",
        "- **Format:** A single image containing the entire 5x5 grid. Exactly 5 columns and exactly 5 rows.",
        "- **Order:** Follow the numbered cell list in strict row-major order, from top-left to bottom-right. Do not reorder, merge, omit, or replace subjects.",
        "- **Aspect Ratio:** The entire image must be perfectly square. Use equal square cells; 128x128 or 256x256 pixels per cell is recommended.",
        "- **Text:** **ABSOLUTELY NO TEXT, NO LETTERS, NO NUMBERS, NO CHARACTERS, NO LABELS, NO WATERMARKS, NO TITLES** anywhere inside the generated image. The IDs and names below are instructions only and must never be rendered.",
        "- **One Subject Per Cell:** Each non-empty cell contains exactly one requested monster or item. No extra props, duplicate subjects, scenery, hands, stands, frames, or UI.",
        "- **Structure:**",
        "    - Each asset must stay fully inside its own square cell with generous padding and no overlap into adjacent cells.",
        "    - Use one perfectly flat, uniform neutral medium-gray background in every cell (#808080 suggested), with no texture, gradient, floor plane, reflection, or cast shadow.",
        "    - Separate all cells with a clean, straight 1px black border to form an exact 5x5 grid. Do not add an ornamental outer frame.",
        "    - Keep visual scale consistent within each category. Preserve a complete, readable silhouette at crop size.",
        "- **Style:**",
        "    - **Refined late 16-bit to early 32-bit console RPG pixel art style** (high-quality SNES/PS1 hybrid).",
        "    - **Ultra-detailed, high-resolution pixel art** with high pixel density and crisp intentional pixel clusters.",
        "    - Sophisticated pixel shading, controlled anti-aliasing, clear highlights and shadows, and strong small-size readability.",
        "    - Materials must be recognizable: faceted crystal, worked metal, patina, bone, scale, fur, cloth folds, magical cores, and gems as appropriate.",
        "    - Monster cells: one full-body creature in a readable three-quarter pose, fully inside the cell, no environment or ground shadow.",
        "    - Item cells: one centered inventory icon at a readable three-quarter or front angle as specified, with no wielder or mannequin.",
        "",
        "## Grid Contents",
        "",
        "Fill cells in the exact order below. `ASSET_ID` and `SAVE_PATH` are production metadata only—never draw them in the image.",
        "",
    ]
    for cell in range(25):
        row = cell // 5 + 1
        column = cell % 5 + 1
        if cell < len(batch):
            entry = batch[cell]
            lines.append(
                f"{cell + 1}. **Row {row}, Column {column}** — "
                f"CATEGORY: {CATEGORY_LABELS[entry['category']]} | "
                f"ASSET_ID: `{entry['id']}` | NAME: {entry['name']} | "
                f"SAVE_PATH: `{entry['path']}` | VISUAL: {entry['visual']}"
            )
        else:
            lines.append(
                f"{cell + 1}. **Row {row}, Column {column}** — EMPTY CELL. Render only the same perfectly flat #808080 background; no subject, symbol, decoration, shadow, or mark."
            )
    lines.extend([
        "",
        "## FINAL VALIDATION BEFORE OUTPUT",
        "",
        "- The canvas is square and visibly divided into exactly 25 equal cells.",
        "- Every requested subject appears once in its assigned cell and nowhere else.",
        "- Empty cells, if any, contain only flat gray.",
        "- No text-like marks, letters, numbers, labels, signatures, logos, or watermarks are visible.",
        "- Nothing crosses a cell border, and every subject can be cropped cleanly into an independent square image.",
        "",
    ])
    lines.extend(f"- {entry['id']}" for entry in batch)
    lines.append("")
    return "\n".join(lines)


def generate_prompt_files(catalog: dict) -> tuple[list[Path], str]:
    entries = image_entries(catalog)
    batches: list[list[dict[str, str]]] = []
    for category in ("monster", "material", "weapon", "armor", "shield", "accessory"):
        category_entries = [entry for entry in entries if entry["category"] == category]
        batches.extend(category_entries[index:index + 25] for index in range(0, len(category_entries), 25))
    PROMPT_DIR.mkdir(parents=True, exist_ok=True)
    for stale_path in PROMPT_DIR.glob("5x5_*.md"):
        stale_path.unlink()
    paths: list[Path] = []
    index_rows: list[list[str]] = []
    for batch_number, batch in enumerate(batches, start=1):
        filename = prompt_filename(batch_number, batch)
        path = PROMPT_DIR / filename
        path.write_text(generate_grid_prompt(batch_number, batch, len(batches)), encoding="utf-8")
        paths.append(path)
        categories = " / ".join(dict.fromkeys(CATEGORY_LABELS[entry["category"]] for entry in batch))
        index_rows.append([
            f"[{filename}]({filename})",
            str(len(batch)),
            categories,
            f"`{batch[0]['id']}`",
            f"`{batch[-1]['id']}`",
            str(25 - len(batch)),
        ])
    index_lines = [
        "# 追加ダンジョン 5x5画像生成プロンプト一覧",
        "",
        "各Markdownファイルを1ファイルずつ外部画像生成AIへ渡してください。生成画像は上段左から右へ、行単位で1〜25番の順です。",
        "",
        f"- 対象画像: {len(entries)}件",
        f"- プロンプト: {len(paths)}ファイル",
        f"- 25件入りバッチ: {sum(len(batch) == 25 for batch in batches)}ファイル",
        f"- カテゴリ末尾の部分バッチ: {sum(len(batch) < 25 for batch in batches)}ファイル",
        f"- 全部分バッチの空マス合計: {sum(25 - len(batch) for batch in batches)}個",
        "- モンスター・素材・各装備カテゴリは、生成品質を安定させるため同じグリッド内で混在させていません。",
        "",
        *table(["プロンプト", "画像数", "カテゴリ", "先頭ID", "末尾ID", "空マス"], index_rows),
        "",
        "## 切り出し時の注意",
        "",
        "- 生成画像を5等分×5等分し、各ファイル内の `SAVE_PATH` に対応させてください。",
        "- IDや名称は生成画像内に描画させず、切り出したファイル名としてのみ使用してください。",
        "- 各カテゴリ末尾バッチの空マスは破棄してください。",
        "",
    ]
    index_text = "\n".join(index_lines)
    (PROMPT_DIR / "README.md").write_text(index_text, encoding="utf-8")
    return paths, index_text


def validate_prompt_files(catalog: dict, paths: list[Path]) -> None:
    expected_entries = image_entries(catalog)
    expected_ids = [entry["id"] for entry in expected_entries]
    expected_metadata = [(entry["id"], entry["path"]) for entry in expected_entries]
    assert len(expected_ids) == 576
    assert len(set(expected_ids)) == len(expected_ids)
    assert len(paths) == math.ceil(len(expected_ids) / 25)
    actual_ids: list[str] = []
    actual_metadata: list[tuple[str, str]] = []
    total_slots = 0
    for path in paths:
        text = path.read_text(encoding="utf-8")
        numbered_cells = re.findall(r"(?m)^(\d+)\. \*\*Row (\d), Column (\d)\*\*", text)
        expected_cells = [(str(index), str((index - 1) // 5 + 1), str((index - 1) % 5 + 1)) for index in range(1, 26)]
        assert numbered_cells == expected_cells, f"{path.name}: grid positions are invalid"
        categories = set(re.findall(r"CATEGORY: ([A-Z]+)", text))
        assert len(categories) == 1, f"{path.name}: categories are mixed"
        metadata = re.findall(r"ASSET_ID: `([^`]+)` .*? SAVE_PATH: `([^`]+)`", text)
        terminal_ids = re.findall(r"(?m)^- ([a-z0-9_]+)$", text)
        assert terminal_ids == [item_id for item_id, _ in metadata], f"{path.name}: terminal ID list is invalid"
        actual_ids.extend(item_id for item_id, _ in metadata)
        actual_metadata.extend(metadata)
        total_slots += len(numbered_cells)
    assert actual_ids == expected_ids, "prompt asset order differs from catalog"
    assert actual_metadata == expected_metadata, "prompt save paths differ from catalog"
    assert total_slots - len(actual_ids) == 24, "unexpected empty-cell count"


def main() -> None:
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    validate(catalog)
    CONTENT_PATH.write_text(generate_content(catalog), encoding="utf-8")
    DOC_PATH.write_text(generate_doc(catalog), encoding="utf-8")
    prompt_paths, _ = generate_prompt_files(catalog)
    validate_prompt_files(catalog, prompt_paths)
    print(f"generated {CONTENT_PATH.relative_to(ROOT)}")
    print(f"generated {DOC_PATH.relative_to(ROOT)}")
    print(f"generated {len(prompt_paths)} prompt files in {PROMPT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
